param ([Parameter(Mandatory = $true)] [string] $Configuration)
$ErrorActionPreference = 'Stop'
$config = Import-Clixml -LiteralPath $Configuration
Start-Transcript -Path $config.transcript -Force
try {
    if ($PID -eq $config.parentPid) { throw 'Expected a separate process' }
    $administrator = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    if (!$administrator) { throw 'The real installer requires an administrative child process' }
    if (Test-Path -LiteralPath $config.runtime) { throw 'Runtime must still be absent when the child starts' }
    Import-Module $config.manifest -Force
    $installer = Get-Command Install-VcRedist
    $module = Get-Module VcRedist
    if ($module.Version.ToString() -ne $config.expectedVersion) { throw 'Incorrect child VcRedist version' }
    $entries = @(Import-Clixml -LiteralPath $config.catalog)
    if ($entries.Count -eq 0) { throw 'No deserialized entries' }
    foreach ($entry in $entries) {
        if ($entry.PSObject.TypeNames[0] -notlike 'Deserialized.*') { throw 'Expected deserialized catalog data' }
        if (!(Test-Path -LiteralPath $entry.Path -PathType Leaf)) { throw 'Serialized installer path is invalid' }
    }
    # This is the unmodified command generated by the PR. Install-VcRedist is the real imported module function.
    & ([scriptblock]::Create($config.command))
    if (!(Test-Path -LiteralPath $config.runtime)) { throw 'Runtime installation failed' }
    [ordered]@{
        pid = $PID
        administrator = $administrator
        shell = "$($PSVersionTable.PSEdition) $($PSVersionTable.PSVersion)"
        module = $module.Path
        version = $module.Version.ToString()
        pathParameter = $installer.Parameters.ContainsKey('Path')
        catalogParameterType = $installer.Parameters['VcList'].ParameterType.FullName
        entries = @($entries | ForEach-Object {
            [ordered]@{ type = $_.PSObject.TypeNames[0]; release = $_.Release; architecture = $_.Architecture; path = $_.Path; sha256 = (Get-FileHash -LiteralPath $_.Path).Hash }
        })
        runtimeInitiallyAbsent = $true
        runtimeInstalled = $true
        runtimeVersion = (Get-Item $config.runtime).VersionInfo.FileVersion
    } | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $config.report -Encoding UTF8
} catch {
    $_ | Format-List * -Force | Out-String | Write-Host
    exit 1
} finally {
    Stop-Transcript
}
